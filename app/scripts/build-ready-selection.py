def add(key,value,unit,steps,checkpoint):
    e=bank[key]
    assert e['status']=='self_check' and not e['existingProblemIds']
    text=e['problemText']; targets=e['targetSubquestions']
    if targets!=['all']:
        # Keep shared conditions and explicit dependencies on earlier subquestions.
        matches=list(re.finditer(r'\((\d+)\)',text))
        if len(targets)==1 and matches and len({m[1] for m in matches})==len(matches):
            q=targets[0]; hit=next(m for m in matches if m[1]==q)
            following=next((m.start() for m in matches if m.start()>hit.start()),len(text))
            part=text[hit.end():following].strip()
            if not re.search(r'\(\d+\)',part):text=text[:matches[0].start()].strip()+'\n'+part
            else:text+='\n【解答するのは小問('+q+')のみです】'
        else:text+='\n【解答するのは小問('+','.join(targets)+')のみです】'
    spec={'n':str(value),'d':'1','unit':unit,'dimension':{'g':'scalar','%':'percent','分':'time','度':'scalar','cm³':'volume'}.get(unit,'scalar')}
    pid='ready-'+key; uid='selection.'+e['selectionKey'].replace('/','.')
    titles=['条件を整理する','求め方を決める','計算する','考え方を確かめる']
    explanation=[{'id':'s'+str(i+1),'title':titles[i],'body':body,'equation':eq} for i,(body,eq) in enumerate(steps)]
    prompt,answer,cpunit=checkpoint
    explanation[-1]['checkpoint']={'prompt':prompt,'answer':{'n':str(answer),'d':'1','unit':cpunit,'dimension':'scalar'}}
    problems.append({'id':pid,'unitId':uid,'category':e['category'],'domain':e['domain'],'text':text.strip(),
      'source':{'title':e['source']['title']+' '+','.join(targets),'url':e['source']['url'],'locator':'Notion 指定小問 '+','.join(targets),'sourceText':e['problemText'],'sourceAnswer':e['sourceAnswerText'],'verification':'本文の条件・答えを確認し、段階解説と途中確認を作成。'},
      'answer':spec,'difficulty':max(1,min(10,e['baseDifficulty']+e['uplift'])),'figureRequired':False,'scopeUnits':e['source']['scopeUnits'],'homeStudy':False,'reviewEligible':False,'expeditionOnly':True,'revision':1,'explanation':{'steps':explanation},'selectionKey':e['selectionKey']})
    units.append({'id':uid,'name':e['learningDecision'],'domain':e['domain'],'definition':e['learningDecision'],'representativeId':pid,'decision':e['learningDecision'],'prerequisites':[]})

